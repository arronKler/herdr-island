#!/bin/bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BRAND="$ROOT/Sources/IslandApp/Resources/Brand"
ICONSET="$ROOT/build/HerdrIsland.iconset"

if ! command -v rsvg-convert >/dev/null; then
    echo "rsvg-convert is required to regenerate icons (brew install librsvg)." >&2
    exit 1
fi
mkdir -p "$ICONSET"

# Derive the transparent mark from the same path as the application icon.
python3 - "$BRAND" <<'PY'
from pathlib import Path
import sys
import xml.etree.ElementTree as ET
from urllib.parse import quote

brand = Path(sys.argv[1])
root = ET.parse(brand / 'HerdrIsland.svg').getroot()
mark = next(node for node in root.iter() if node.get('id') == 'island-mark')
viewbox = mark.attrib['data-viewbox']
path = mark.attrib['d']
(brand / 'HerdrIslandMark.svg').write_text(
    '<!-- Generated by Scripts/make-icons.sh; edit HerdrIsland.svg. -->\n'
    f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{viewbox}">\n'
    f'  <path fill="#000000" d="{path}"/>\n'
    '</svg>\n'
)
# An embedded mask also works when design previews are opened as file:// URLs.
mask = quote(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{viewbox}"><path d="{path}"/></svg>', safe='')
(brand / 'HerdrIslandMark.css').write_text(
    '/* Generated by Scripts/make-icons.sh; edit HerdrIsland.svg. */\n'
    '.herdr-brand-mark{display:inline-block;background:currentColor;'
    f'mask:url("data:image/svg+xml,{mask}") center/contain no-repeat;'
    '}\n'
)
PY

for name in HerdrIsland HerdrIslandMark; do
    rsvg-convert --format=pdf --output="$BRAND/$name.pdf" "$BRAND/$name.svg"
done

for size in 16 32 128 256 512; do
    for scale in 1 2; do
        suffix=""
        if [ "$scale" -eq 2 ]; then suffix="@2x"; fi
        pixels=$((size * scale))
        rsvg-convert --width="$pixels" --height="$pixels" \
            --output="$ICONSET/icon_${size}x${size}${suffix}.png" "$BRAND/HerdrIsland.svg"
    done
done
iconutil --convert icns --output "$ROOT/Resources/HerdrIsland.icns" "$ICONSET"
echo "Generated vector PDFs, template SVG, and Resources/HerdrIsland.icns"
